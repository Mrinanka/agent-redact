// npm run plugin:build: copies src/checker and src/core into plugin/hooks/lib/, because an installed
// plugin gets no build step and a mod can only import files inside its own folder.
//   node tools/plugin/build.ts           write the copies
//   node tools/plugin/build.ts --check   fail if they differ from the sources (CI)
// The copies are byte for byte the sources; nothing is changed on the way.

import fs from 'node:fs'
import path from 'node:path'

const MAP: [from: string, to: string][] = [
  ['src/checker', 'plugin/hooks/lib/checker'],
  ['src/core', 'plugin/hooks/lib/core'],
]

/** An install may copy plugin/ alone, so the licences and credits go with it. */
const SINGLE: [from: string, to: string][] = [
  ['LICENSE', 'plugin/LICENSE'],
  ['NOTICE', 'plugin/NOTICE'],
  ['THIRD_PARTY_LICENSES', 'plugin/THIRD_PARTY_LICENSES'],
]

export type PlannedFile = { from: string; to: string; content: string }

export function listFiles(dir: string): string[] {
  if (!fs.existsSync(dir)) return []
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(e => (e.isDirectory() ? listFiles(path.join(dir, e.name)) : [path.join(dir, e.name)]))
}

export function buildPlan(root: string): { files: PlannedFile[]; stale: string[] } {
  const files: PlannedFile[] = []
  const stale: string[] = []
  for (const [from, to] of MAP) {
    const fromDir = path.join(root, ...from.split('/'))
    const toDir = path.join(root, ...to.split('/'))
    const made = new Set<string>()
    for (const file of listFiles(fromDir)) {
      const target = path.join(toDir, path.relative(fromDir, file))
      made.add(target)
      files.push({ from: file, to: target, content: fs.readFileSync(file, 'utf8') })
    }
    for (const file of listFiles(toDir)) if (!made.has(file) && !file.endsWith('README.md')) stale.push(file)
  }
  for (const [from, to] of SINGLE) {
    const source = path.join(root, ...from.split('/'))
    files.push({ from: source, to: path.join(root, ...to.split('/')), content: fs.readFileSync(source, 'utf8') })
  }
  return { files, stale }
}

function main(): void {
  const root = path.join(import.meta.dirname, '..', '..')
  const check = process.argv.includes('--check')
  const { files, stale } = buildPlan(root)
  const drift: string[] = []
  for (const f of files) {
    const have = fs.existsSync(f.to) ? fs.readFileSync(f.to, 'utf8') : undefined
    if (have !== f.content) drift.push(path.relative(root, f.to))
  }
  if (check) {
    for (const s of stale) drift.push(`${path.relative(root, s)} (no source)`)
    if (drift.length > 0) {
      console.error(`plugin/hooks/lib is out of date (${drift.length} files). Run: npm run plugin:build\n  ${drift.slice(0, 20).join('\n  ')}`)
      process.exit(1)
    }
    console.log(`plugin/hooks/lib is current (${files.length} files)`)
    return
  }
  for (const f of files) {
    fs.mkdirSync(path.dirname(f.to), { recursive: true })
    fs.writeFileSync(f.to, f.content)
  }
  for (const s of stale) fs.rmSync(s)
  const readme = path.join(root, 'plugin', 'hooks', 'lib', 'README.md')
  fs.mkdirSync(path.dirname(readme), { recursive: true })
  fs.writeFileSync(readme, 'Generated by `npm run plugin:build` from `src/checker` and `src/core`. Do not edit: change the sources and run the build.\n')
  console.log(`wrote ${files.length} files, removed ${stale.length}`)
}

if (import.meta.main) main()
