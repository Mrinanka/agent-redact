// npm run rules:build: converts the vendored Gitleaks rules into
// src/checker/rules.generated.ts. `--check` fails if the committed file is stale.

import fs from 'node:fs'
import path from 'node:path'
import { convertRule, keywordNote, toSpec } from '../../src/checker/convert.ts'
import type { AllowList, CompiledRule, RawRule, Rejection } from '../../src/checker/types.ts'
import { parseToml, type TomlTable } from './toml.ts'

export const GITLEAKS = {
  version: 'v8.30.1',
  commit: '83d9cd684c87d95d656c1458ef04895a7f1cbd8e',
}

const root = path.join(import.meta.dirname, '..', '..')
export const TOML_PATH = path.join(root, 'third_party', 'gitleaks', 'gitleaks.toml')
export const GENERATED_PATH = path.join(root, 'src', 'checker', 'rules.generated.ts')

export type Built = {
  rules: CompiledRule[]
  rejections: Rejection[]
  warnings: string[]
  globalAllow: AllowList
}

export function buildRules(tomlText: string): Built {
  const doc = parseToml(tomlText)
  const rules: CompiledRule[] = []
  const rejections: Rejection[] = []
  const warnings: string[] = []
  for (const raw of doc.rules as TomlTable[]) {
    const result = convertRule(raw as unknown as RawRule)
    if ('rejection' in result) rejections.push(result.rejection)
    else {
      warnings.push(...result.warnings)
      const note = keywordNote(result.rule.keywords, (raw as { keywords?: string[] }).keywords)
      rules.push({ ...result.rule, keywordNote: note })
    }
  }
  const g = doc.allowlist as { regexes?: string[]; stopwords?: string[] }
  const globalAllow: AllowList = {
    target: 'secret',
    regexes: (g.regexes ?? []).map(r => toSpec(r)),
    stopwords: (g.stopwords ?? []).map(s => s.toLowerCase()),
    and: false,
  }
  return { rules, rejections, warnings, globalAllow }
}

export function render(built: Built): string {
  const j = (v: unknown): string => JSON.stringify(v, null, 1)
  return [
    '// Generated by `npm run rules:build` from third_party/gitleaks/gitleaks.toml. Do not edit.',
    `// Gitleaks ${GITLEAKS.version} (${GITLEAKS.commit}), MIT licence: see THIRD_PARTY_LICENSES.`,
    '',
    "import type { AllowList, CompiledRule, Rejection } from './types.ts'",
    '',
    `export const GITLEAKS_VERSION = ${j(GITLEAKS.version)}`,
    `export const GITLEAKS_COMMIT = ${j(GITLEAKS.commit)}`,
    `export const GLOBAL_ALLOW: AllowList = ${j(built.globalAllow)}`,
    `export const RULES: CompiledRule[] = ${j(built.rules)}`,
    `export const REJECTIONS: Rejection[] = ${j(built.rejections)}`,
    `export const BUILD_WARNINGS: string[] = ${j(built.warnings)}`,
    '',
  ].join('\n')
}

export function expected(): string {
  return render(buildRules(fs.readFileSync(TOML_PATH, 'utf8')))
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  const text = expected()
  if (process.argv.includes('--check')) {
    const have = fs.existsSync(GENERATED_PATH) ? fs.readFileSync(GENERATED_PATH, 'utf8') : ''
    if (have !== text) {
      console.error('src/checker/rules.generated.ts is stale: run `npm run rules:build`')
      process.exit(1)
    }
    console.log('rules.generated.ts is current')
  } else {
    fs.writeFileSync(GENERATED_PATH, text)
    const built = buildRules(fs.readFileSync(TOML_PATH, 'utf8'))
    console.log(`wrote ${built.rules.length} rules, ${built.rejections.length} rejected`)
    for (const r of built.rejections) console.log(`  rejected ${r.id}: ${r.reason}`)
    for (const w of built.warnings) console.log(`  warning ${w}`)
  }
}
